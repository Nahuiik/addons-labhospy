    def _generate_recommendations(self, context):
        """
        Generate recommendations based on the quotation context.
        
        Args:
            context (dict): Context data
            
        Returns:
            list: List of recommendations
        """
        recommendations = []
        
        amount_total = context.get('amount_total', 0)
        if amount_total > 10000:
            recommendations.append(_('Consider offering payment terms for large orders'))
        
        lines = context.get('order_lines', [])
        if len(lines) > 5:
            recommendations.append(_('Multiple products detected - consider bundle pricing'))
        
        customer_category = context.get('customer_category', [])
        if 'VIP' in customer_category or 'VIP Client' in customer_category:
            recommendations.append(_('VIP customer - prioritize this quotation'))
        
        return recommendations

    def _process_ia_result(self, result):
        """
        Process the result from the AI agent.
        
        Args:
            result (dict): Result from AI agent
            
        Returns:
            dict: Processed result
        """
        if not result.get('success'):
            return result
        
        suggestion = result.get('suggestion', '')
        recommendations = result.get('recommendations', [])
        
        # Combine suggestion and recommendations
        if recommendations:
            suggestion += '\n\n' + _('Additional Recommendations:') + '\n'
            for i, rec in enumerate(recommendations, 1):
                suggestion += f'{i}. {rec}\n'
        
        result['suggestion'] = suggestion
        
        return result

    def action_get_ia_suggestion(self):
        """
        Action method to trigger AI suggestion generation.
        Can be called from a button in the view.
        
        Returns:
            dict: Action result with notification
        """
        self.ensure_one()
        
        result = self.get_ia_suggestion()
        
        if result.get('success'):
            message = _('AI suggestion generated successfully. Please refresh the page to see the suggestion.')
            message_type = 'success'
        else:
            message = result.get('message', _('Error generating AI suggestion'))
            message_type = 'danger'
        
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _('AI Suggestion'),
                'message': message,
                'type': message_type,
                'sticky': False,
            }
        }

