    def get_ia_suggestion(self):
        """
        Main method to get AI suggestion for the quotation.
        This method can invoke an AI agent or use its result.
        
        Returns:
            dict: Dictionary containing the AI suggestion data
        """
        self.ensure_one()
        
        if not self.ia_enabled:
            return {
                'success': False,
                'message': _('AI suggestions are disabled for this quotation'),
            }

        try:
            # Update state to processing
            self.write({'ia_suggestion_state': 'processing'})

            # Prepare context for AI agent
            context = self._prepare_ia_context()

            # Invoke AI agent or get suggestion
            suggestion_result = self._invoke_ia_agent(context)

            # Process and store the result
            result = self._process_ia_result(suggestion_result)

            # Update the quotation with the suggestion
            self.write({
                'ia_suggestion_text': result.get('suggestion', ''),
                'ia_suggestion_date': fields.Datetime.now(),
                'ia_suggestion_state': 'completed' if result.get('success') else 'error',
            })

            return result

        except Exception as e:
            _logger.error("Error getting IA suggestion: %s", str(e))
            self.write({
                'ia_suggestion_state': 'error',
                'ia_suggestion_text': _('Error generating AI suggestion: %s') % str(e),
            })
            return {
                'success': False,
                'message': _('Error generating AI suggestion: %s') % str(e),
                'error': str(e),
            }

    def _prepare_ia_context(self):
        """
        Prepare the context data for the AI agent.
        
        Returns:
            dict: Context data including quotation details
        """
        self.ensure_one()
        
        # Get order lines information
        order_lines_data = []
        for line in self.order_line:
            order_lines_data.append({
                'product': line.product_id.name if line.product_id else '',
                'quantity': line.product_uom_qty,
                'price_unit': line.price_unit,
                'discount': line.discount,
                'subtotal': line.price_subtotal,
            })

        context = {
            'quotation_name': self.name,
            'customer': self.partner_id.name if self.partner_id else '',
            'customer_category': self.partner_id.category_id.mapped('name') if self.partner_id else [],
            'date_order': self.date_order.isoformat() if self.date_order else '',
            'amount_untaxed': self.amount_untaxed,
            'amount_tax': self.amount_total - self.amount_untaxed,
            'amount_total': self.amount_total,
            'currency': self.currency_id.name if self.currency_id else '',
            'order_lines': order_lines_data,
            'payment_term': self.payment_term_id.name if self.payment_term_id else '',
            'state': self.state,
        }

        return context

